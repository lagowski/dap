"""Tests for the hub export's client-name scrubber (#1016): allowlist, replacement, refusal."""

from __future__ import annotations

from pathlib import Path

import pytest
from dap_cli.hub_names import BUILTIN, Scrubber, Unclear, load_public_names


def scrub(text: str, *context: str) -> str:
    return Scrubber([text, *context]).scrub(text)


def test_a_planted_client_name_becomes_client() -> None:
    assert scrub("Summarise the issue for Acme Logistics") == "Summarise the issue for client"


def test_a_single_name_mid_sentence_becomes_client() -> None:
    assert scrub("Send the report to Globex every week.") == "Send the report to client every week."


def test_a_name_at_a_sentence_start_followed_by_a_name_is_one_name() -> None:
    assert scrub("Acme Logistics ships parcels.") == "client ships parcels."


def test_a_sentence_start_name_used_as_a_name_elsewhere_is_replaced() -> None:
    assert scrub("Initech wants a summary. Write it for Initech.") == (
        "client wants a summary. Write it for client."
    )


def test_allowlisted_names_survive() -> None:
    text = "Read the GitHub issue and ask Claude for a JSON answer in Python."
    assert scrub(text) == text


def test_allowlisted_phrase_survives() -> None:
    text = "Run it with Claude Code and GitHub Actions."
    assert scrub(text) == text


def test_jinja_survives_untouched() -> None:
    text = "Title: {{ issue_title }}\n{% if Acme %}Body: {{ issue_body }}{% endif %}"
    assert scrub(text) == text


def test_code_spans_and_identifiers_are_not_names() -> None:
    text = "Set `FooBar` and read state.Acme_id or H1 at owner/Repo, then run jq -Rs on it."
    assert scrub(text) == text


def test_sentence_initial_ordinary_word_is_not_a_name() -> None:
    assert (
        scrub("Summarise the issue. Rank them by age.") == "Summarise the issue. Rank them by age."
    )


def test_all_caps_emphasis_of_an_ordinary_word_survives_and_an_acronym_does_not() -> None:
    assert scrub("Return ONLY the list for ACME.") == "Return ONLY the list for client."


def test_camel_case_name_is_replaced() -> None:
    assert scrub("Post it to the ShopRite board.") == "Post it to the client board."


def test_a_lower_camel_word_is_an_identifier() -> None:
    assert scrub("Sort by updatedAt on macOS.") == "Sort by updatedAt on macOS."


def test_markdown_headings_start_a_sentence_and_rst_literals_are_code() -> None:
    text = "## Suggested approach\n\nUse ``## Risks`` as a heading.\n> Generated by the pipeline."
    assert scrub(text) == text


def test_a_markdown_task_item_starts_a_sentence_and_csv_is_a_standard() -> None:
    text = "- [ ] Each report has a CSV download\n- [x] Empty reports hold a header row"
    assert scrub(text) == text
    assert scrub("- [ ] Send it to Globex") == "- [ ] Send it to client"


def test_an_unclosed_template_tag_is_unclear() -> None:
    with pytest.raises(Unclear):
        scrub("Hello {{ name for Acme")


def test_unclear_never_echoes_the_value() -> None:
    with pytest.raises(Unclear) as exc:
        scrub("Hello {{ Initech")
    assert "Initech" not in str(exc.value)


def test_public_names_yaml_extends_the_allowlist(tmp_path: Path) -> None:
    path = tmp_path / "public-names.yaml"
    path.write_text("products:\n  - Globex\n  - Acme Logistics\nother:\n  - Initech\n")
    public = load_public_names(path)
    text = "Ask Globex, Initech and Acme Logistics, then use GitHub."
    assert Scrubber([text], public).scrub(text) == text
    # the built-in set is unchanged
    assert (
        Scrubber([text], BUILTIN).scrub(text) == "Ask client, client and client, then use GitHub."
    )


@pytest.mark.parametrize("content", ["- just\n- a list\n", "group: not-a-list\n", "a: [1, 2]\n"])
def test_a_malformed_public_names_file_is_refused(tmp_path: Path, content: str) -> None:
    path = tmp_path / "public-names.yaml"
    path.write_text(content)
    with pytest.raises(ValueError, match="bad --public-names"):
        load_public_names(path)


def test_a_bad_group_is_named_as_written(tmp_path: Path) -> None:
    path = tmp_path / "public-names.yaml"
    path.write_text("products: 5\n")
    with pytest.raises(ValueError, match=r"^bad --public-names: group 'products' must be a list"):
        load_public_names(path)


def test_a_missing_public_names_file_is_refused(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="bad --public-names"):
        load_public_names(tmp_path / "missing.yaml")
